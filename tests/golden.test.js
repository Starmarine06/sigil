test("analyze exposes structured sections (evidence tree)", () => {
  const result = analyze(fixture("claude-export.json"));
  assert.ok(result.sections);
  assert.ok(Array.isArray(result.sections.keyPhrases));
  assert.ok(Array.isArray(result.sections.code));
  assert.ok(typeof result.sections.stats.tokens === "number");
  assert.ok(Array.isArray(result.sections.transcript));
  assert.ok(result.sections.representative.every((r) => typeof r.score === "number"));
});